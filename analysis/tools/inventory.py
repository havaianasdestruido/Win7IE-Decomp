#!/usr/bin/env python3
"""Inventory bin/ and extract reproducible PE metadata with GNU objdump.

Usage: python3 analysis/tools/inventory.py
Outputs JSON evidence under analysis/report/generated and Markdown/module skeletons.
The script reads but never writes bin/. GNU objdump 2.40 output is parsed
conservatively; raw command output is retained for audit.
"""
from __future__ import annotations
import hashlib, json, os, re, subprocess, sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT=Path(__file__).resolve().parents[2]; BIN=ROOT/'bin'; REPORT=ROOT/'analysis/report'; GEN=REPORT/'generated'; SRC=ROOT/'src'
PE_EXT={'.dll','.exe','.mui'}

def run(*args):
 p=subprocess.run(args,cwd=ROOT,stdout=subprocess.PIPE,stderr=subprocess.PIPE,text=True,errors='replace')
 return {'argv':list(args),'exit_code':p.returncode,'stdout':p.stdout,'stderr':p.stderr}
def sha(p):
 h=hashlib.sha256()
 with p.open('rb') as f:
  for b in iter(lambda:f.read(1<<20),b''): h.update(b)
 return h.hexdigest()
def module_name(p):
 rel=p.relative_to(BIN)
 if p.suffix.lower()=='.mui': return '_'.join(rel.parts[:-1]+(p.name.replace('.','_'),))
 return p.stem.replace('.','_')
def parse_pe(text):
 def one(pattern, default=None, flags=re.M):
  m=re.search(pattern,text,flags); return m.group(1).strip() if m else default
 imports=defaultdict(list); cur=None; exports=[]
 for line in text.splitlines():
  m=re.search(r'DLL Name:\s*(\S+)',line)
  if m: cur=m.group(1); continue
  m=re.match(r'\s*[0-9a-fA-F]+\s+(?:[0-9]+|[0-9a-fA-F]+)\s+(.+?)\s*$',line)
  if cur and m:
   sym=m.group(1).strip()
   # Descriptor rows also match the loose address prefix; they are not symbols.
   if re.fullmatch(r'(?:[0-9a-fA-F]+\s+){3}[0-9a-fA-F]+',sym): continue
   if sym == '<none>': sym = '(ordinal-only import; name unavailable)'
   if sym and not sym.startswith(('Time/Date','The ')): imports[cur].append(sym)
 # objdump export table ordinal rows
 in_exports=False
 for line in text.splitlines():
  if '[Ordinal/Name Pointer] Table' in line: in_exports=True; continue
  if in_exports:
   m=re.match(r'\s*\[\s*\d+\]\s+(.+)',line)
   if m: exports.append(m.group(1).strip())
   elif exports and not line.strip(): break
 sections=[]
 for m in re.finditer(r'^\s*\d+\s+(\S+)\s+([0-9a-fA-F]+)\s+([0-9a-fA-F]+)\s+([0-9a-fA-F]+)\s+([0-9a-fA-F]+)',text,re.M):
  sections.append({'name':m.group(1),'size':int(m.group(2),16),'vma':m.group(3),'file_offset':int(m.group(5),16)})
 return {'format':one(r'^.*file format\s+(\S+)'),'architecture':one(r'^architecture:\s*([^,]+)'),
 'entry_point':one(r'^start address\s+(\S+)'),'timestamp':one(r'^Time/Date\s+(.+)$'),
 'image_base':one(r'^ImageBase\s+([0-9a-fA-F]+)$'),'subsystem':one(r'^Subsystem\s+(.+)$'),
 'imports':dict(imports),'exports':sorted(set(exports)),'sections':sections,
 'clr':bool(re.search(r'Entry e\s+(?!0+\s+0+)[0-9a-fA-F]+\s+(?!0+\s*$)[0-9a-fA-F]+',text,re.M))}

def main():
 GEN.mkdir(parents=True,exist_ok=True); SRC.mkdir(exist_ok=True)
 files=[]; pes=[]
 for p in sorted(x for x in BIN.rglob('*') if x.is_file()):
  rel=p.relative_to(ROOT).as_posix(); data=p.read_bytes()[:16]
  rec={'path':rel,'size':p.stat().st_size,'sha256':sha(p),'magic':data.hex(),'kind':'PE/COFF' if data[:2]==b'MZ' else ('XML/text' if data.lstrip().startswith((b'<',b'{')) else 'data/text')}
  if data[:2]==b'MZ':
   x=run('objdump','-x',str(p)); rec.update(parse_pe(x['stdout'])); rec['objdump_exit']=x['exit_code']
   raw=GEN/(p.relative_to(BIN).as_posix().replace('/','__')+'.objdump.txt'); raw.write_text(x['stdout']+('\nSTDERR:\n'+x['stderr'] if x['stderr'] else ''),encoding='utf-8')
   pes.append(rec)
  files.append(rec)
 (GEN/'inventory.json').write_text(json.dumps(files,indent=2,sort_keys=True)+'\n')
 # inventory
 lines=['# Binary inventory','','Generated by `analysis/tools/inventory.py`. SHA-256 covers the unmodified input bytes.','',f'Files: **{len(files)}**; PE/COFF images: **{len(pes)}**; total bytes: **{sum(x["size"] for x in files):,}**.','','| Path | Bytes | SHA-256 | Format / architecture | Status |','|---|---:|---|---|---|']
 for x in files:
  fmt=(x.get('format') or x['kind'])+('/'+x.get('architecture','') if x.get('architecture') else '')
  lines.append(f"| `{x['path']}` | {x['size']:,} | `{x['sha256']}` | {fmt} | {'structurally analyzed' if x['kind']=='PE/COFF' else 'inventoried/decoded as applicable'} |")
 (REPORT/'inventory.md').write_text('\n'.join(lines)+'\n')
 # API map
 lines=['# Consolidated API map','','Evidence: `analysis/report/generated/*.objdump.txt`; names are PE import/export table observations, not inferred prototypes.','']
 deps=[]
 for x in pes:
  lines += [f"## `{x['path']}`",'',f"Architecture: `{x.get('architecture')}`; entry: `{x.get('entry_point')}`; CLR metadata: **{x.get('clr')}**.",'']
  if x['imports']:
   for dll,names in sorted(x['imports'].items()):
    clean=sorted(set(names)); lines.append(f"- `{dll}` ({len(clean)} names): "+', '.join(f'`{n}`' for n in clean))
    deps.append({'source':x['path'],'target':dll,'symbols':clean})
  else: lines.append('- No named imports recovered (resource-only image or parser limitation).')
  lines.append('- Exports: '+(', '.join(f'`{e}`' for e in x['exports']) if x['exports'] else 'none recovered.'))
  lines.append('')
 (REPORT/'api-map.md').write_text('\n'.join(lines)+'\n'); (GEN/'dependencies.json').write_text(json.dumps(deps,indent=2)+'\n')
 # source module evidence pages
 for x in pes:
  p=ROOT/x['path']; name=module_name(p); d=SRC/name; d.mkdir(parents=True,exist_ok=True)
  sec='\n'.join(f"| `{s['name']}` | 0x{s['size']:x} | `0x{s['vma']}` | 0x{s['file_offset']:x} |" for s in x['sections']) or '| (not parsed) | | | |'
  imports='\n'.join(f"- `{k}`: {len(set(v))} named imports" for k,v in sorted(x['imports'].items())) or '- None recovered.'
  text=f"# {p.name}\n\n> Evidence status: header, section, and import/export facts below are verified against SHA-256 `{x['sha256']}` using GNU objdump. Function types and behavior have not been guessed.\n\n## Image\n\n- Format: `{x.get('format')}`\n- Architecture: `{x.get('architecture')}`\n- Entry point: `{x.get('entry_point')}`\n- Timestamp field: `{x.get('timestamp')}` (untrusted PE metadata)\n- CLR header present: `{x.get('clr')}`\n\n## Sections\n\n| Name | Size | VMA | File offset |\n|---|---:|---:|---:|\n{sec}\n\n## Dependencies\n\n{imports}\n\n## Reconstruction status\n\nNo compatibility implementation is emitted: available evidence is insufficient to assign semantics safely. Raw structural evidence is in `analysis/report/generated/{p.relative_to(BIN).as_posix().replace('/','__')}.objdump.txt`.\n"
  (d/'README.md').write_text(text)
  (d/'interfaces.h').write_text(f"#pragma once\n/* Evidence ledger for {p.name}. No verified callable declarations recovered yet. */\n")
 print(f'Inventoried {len(files)} files, parsed {len(pes)} PE images.')
if __name__=='__main__': main()
