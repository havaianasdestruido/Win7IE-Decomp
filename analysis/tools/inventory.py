#!/usr/bin/env python3
"""Phase 0 corpus inventory, PE structural extraction, and evidence ledgers.

Usage: python3 analysis/tools/inventory.py

Reads every file under bin/, hashes it, classifies it, and (for PE/COFF
images) retains GNU objdump -x output plus a stdlib PE parse. Never writes
inside bin/.
"""
from __future__ import annotations

import hashlib
import json
import os
import subprocess
import sys
from collections import Counter, defaultdict
from datetime import datetime, timezone
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
sys.path.insert(0, str(TOOLS))

from pe import PeImage, parse_pe  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
BIN = ROOT / "bin"
REPORT = ROOT / "analysis" / "report"
GEN = REPORT / "generated"
SRC = ROOT / "src"


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def classify(path: Path, header: bytes) -> str:
    if header.startswith(b"MZ"):
        return "PE/COFF"
    if header.startswith(b"{\\rtf"):
        return "RTF"
    if header[:4] == b"\x00\x00\x01\x00":
        return "ICO"
    if header.startswith(b"\xff\xfe"):
        return "UTF-16LE text"
    stripped = header.lstrip(b"\xef\xbb\xbf \t\r\n")
    if stripped.startswith(b"<?xml") or stripped.startswith(b"<"):
        return "XML"
    if path.suffix.lower() in {".md", ".txt"} or path.name == "LICENSE":
        return "text"
    try:
        header.decode("ascii")
        return "text"
    except UnicodeDecodeError:
        return "data"


def module_name(path: Path) -> str:
    rel = path.relative_to(BIN)
    if path.suffix.lower() == ".mui":
        return "_".join(rel.parts[:-1] + (path.name.replace(".", "_"),))
    return path.stem.replace(".", "_")


def objdump_raw_name(path: Path) -> str:
    return path.relative_to(BIN).as_posix().replace("/", "__") + ".objdump.txt"


def run_objdump(path: Path) -> dict[str, object]:
    proc = subprocess.run(
        ["objdump", "-x", str(path)],
        cwd=ROOT,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        errors="replace",
        check=False,
    )
    return {"argv": ["objdump", "-x", str(path)], "exit_code": proc.returncode, "stdout": proc.stdout, "stderr": proc.stderr}


def pe_summary(image: PeImage) -> dict[str, object]:
    pdb = [item.pdb_path for item in image.debug if item.pdb_path]
    return {
        "format": image.format,
        "machine": image.machine_name,
        "entry_rva": f"0x{image.address_of_entry_point:x}",
        "entry_va": f"0x{image.entry_point_va():x}",
        "image_base": f"0x{image.image_base:x}",
        "subsystem": image.subsystem_name,
        "linker_version": image.linker_version,
        "os_version": image.os_version,
        "characteristics": image.characteristics_names,
        "dll_characteristics": image.dll_characteristics_names,
        "section_names": [section.name for section in image.sections],
        "import_dlls": sorted({item.dll for item in image.imports}),
        "delay_import_dlls": sorted({item.dll for item in image.delay_imports}),
        "export_names": [item.display() for item in image.exports],
        "export_count": len(image.exports),
        "has_clr": image.has_clr,
        "pdb": pdb,
        "timestamp_unix": image.timestamp,
        "timestamp_utc": datetime.fromtimestamp(image.timestamp, tz=timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        if image.timestamp
        else "1970-01-01T00:00:00Z",
    }


def grouped_symbols(symbols) -> dict[str, list[str]]:
    grouped: dict[str, list[str]] = defaultdict(list)
    for item in symbols:
        grouped[item.dll].append(item.display())
    for dll, names in grouped.items():
        grouped[dll] = sorted(set(names), key=lambda name: (name.startswith("ordinal:"), name.lower()))
    return dict(sorted(grouped.items(), key=lambda kv: kv[0].lower()))


def assert_not_bin(path: Path) -> None:
    try:
        path.relative_to(BIN)
    except ValueError:
        return
    raise RuntimeError(f"refusing to write inside bin/: {path}")


def write_text(path: Path, text: str) -> None:
    assert_not_bin(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def write_json(path: Path, payload: object) -> None:
    write_text(path, json.dumps(payload, indent=2, sort_keys=True) + "\n")


def render_inventory_md(files: list[dict]) -> str:
    pe_files = [item for item in files if item["kind"] == "PE/COFF"]
    kinds = Counter(item["kind"] for item in files)
    lines = [
        "# Binary inventory",
        "",
        "Generated by `analysis/tools/inventory.py`. SHA-256 covers the unmodified input bytes in `bin/`.",
        "",
        f"Files: **{len(files)}**; PE/COFF images: **{len(pe_files)}**; total bytes: **{sum(item['size'] for item in files):,}**.",
        "",
        "## Classification summary",
        "",
        "| Kind | Count | Bytes |",
        "|---|---:|---:|",
    ]
    by_kind: dict[str, list[dict]] = defaultdict(list)
    for item in files:
        by_kind[item["kind"]].append(item)
    for kind in sorted(by_kind):
        group = by_kind[kind]
        lines.append(f"| {kind} | {len(group)} | {sum(x['size'] for x in group):,} |")
    lines += [
        "",
        "Kind counts: " + ", ".join(f"{k}={v}" for k, v in sorted(kinds.items())) + ".",
        "",
        "## Cryptographic lock",
        "",
        "| Path | Bytes | SHA-256 | Kind | Magic (16 bytes) | Format / architecture | Status |",
        "|---|---:|---|---|---|---|---|",
    ]
    for item in files:
        pe = item.get("pe") or {}
        fmt = pe.get("format") or item["kind"]
        if pe.get("machine"):
            fmt = f"{fmt}/{pe['machine']}"
        status = "structurally analyzed" if item["kind"] == "PE/COFF" else "inventoried"
        lines.append(
            f"| `{item['path']}` | {item['size']:,} | `{item['sha256']}` | {item['kind']} | `{item['magic']}` | {fmt} | {status} |"
        )
    lines.append("")
    return "\n".join(lines)


def render_api_map_md(records: list[dict]) -> str:
    lines = [
        "# Consolidated API map",
        "",
        "Evidence: `analysis/report/generated/*.objdump.txt` plus the stdlib PE parser in `analysis/tools/pe.py`.",
        "Names and ordinals are Import/Export Address Table observations, not inferred prototypes.",
        "",
    ]
    for item in records:
        pe = item["pe"]
        image: PeImage = item["_image"]
        lines += [
            f"## `{item['path']}`",
            "",
            f"- Format: `{pe['format']}`; machine: `{pe['machine']}`; entry: `{pe['entry_va']}` (RVA `{pe['entry_rva']}`).",
            f"- ImageBase: `{pe['image_base']}`; subsystem: `{pe['subsystem']}`; CLR metadata: **{pe['has_clr']}**.",
            f"- PDB: {', '.join(f'`{name}`' for name in pe['pdb']) if pe['pdb'] else 'none recovered'}.",
            "",
        ]
        static = grouped_symbols(image.imports)
        if static:
            lines.append("### Static imports")
            lines.append("")
            for dll, names in static.items():
                joined = ", ".join(f"`{name}`" for name in names)
                lines.append(f"- `{dll}` ({len(names)}): {joined}")
            lines.append("")
        else:
            lines.append("No named static imports recovered (resource-only image or empty IAT).")
            lines.append("")
        delayed = grouped_symbols(image.delay_imports)
        if delayed:
            lines.append("### Delay-load imports")
            lines.append("")
            for dll, names in delayed.items():
                joined = ", ".join(f"`{name}`" for name in names)
                lines.append(f"- `{dll}` ({len(names)}): {joined}")
            lines.append("")
        if image.exports:
            export_list = ", ".join(f"`{symbol.display()}`" for symbol in image.exports)
            lines.append(f"### Exports ({len(image.exports)})")
            lines.append("")
            lines.append(export_list)
            lines.append("")
        else:
            lines.append("Exports: none recovered.")
            lines.append("")
    return "\n".join(lines)


def render_dependencies_md(records: list[dict], edges: list[dict]) -> str:
    static_targets = Counter(edge["target"] for edge in edges if edge["kind"] == "static")
    delay_targets = Counter(edge["target"] for edge in edges if edge["kind"] == "delay-load")
    lines = [
        "# Dependencies",
        "",
        "Machine-readable edges are in `analysis/report/generated/dependencies.json`.",
        "Symbol names are listed in `api-map.md`. A static or delay-load import records linkage, not a proven runtime call.",
        "",
        "## Graph size",
        "",
        f"- Static import edges: **{sum(1 for e in edges if e['kind'] == 'static')}**",
        f"- Delay-load import edges: **{sum(1 for e in edges if e['kind'] == 'delay-load')}**",
        f"- Distinct static targets: **{len(static_targets)}**",
        f"- Distinct delay-load targets: **{len(delay_targets)}**",
        "",
        "## Most-referenced static DLLs",
        "",
        "| Imported module | Importers |",
        "|---|---:|",
    ]
    for dll, count in static_targets.most_common():
        lines.append(f"| `{dll}` | {count} |")
    if delay_targets:
        lines += [
            "",
            "## Delay-load targets",
            "",
            "| Imported module | Importers |",
            "|---|---:|",
        ]
        for dll, count in delay_targets.most_common():
            lines.append(f"| `{dll}` | {count} |")
    lines += [
        "",
        "## Per-image linkage",
        "",
        "| Image | Static DLLs | Delay-load DLLs | Exports | CLR |",
        "|---|---|---|---:|:---:|",
    ]
    for item in records:
        pe = item["pe"]
        static = ", ".join(f"`{name}`" for name in pe["import_dlls"]) or "—"
        delayed = ", ".join(f"`{name}`" for name in pe["delay_import_dlls"]) or "—"
        lines.append(
            f"| `{item['path']}` | {static} | {delayed} | {pe['export_count']} | {'yes' if pe['has_clr'] else 'no'} |"
        )
    lines += [
        "",
        "## Verified patterns",
        "",
        "Native modules predominantly import Windows system facilities (`KERNEL32`, `USER32`, `ADVAPI32`, `OLE32`, `OLEAUT32`, `RPCRT4`, `SHLWAPI`) and the Microsoft C runtime. COM-style exports (`DllGetClassObject`, `DllCanUnloadNow`, registration entrypoints) occur throughout the diagnostics/tooling DLL set.",
        "",
        "`iediagcmd.exe` depends on `mscoree.dll!_CorExeMain`, making the CLR a verified runtime prerequisite. The MUI satellites have empty import tables and are associated to base modules by filename/locale convention (an inferred deployment relationship).",
        "",
        "Delay-load descriptors are present on `iexplore.exe` (`IEFRAME.dll`, ordinal-only), `IEShims.dll`, `ieproxy.dll`, `pdm.dll`, `perf_nt.dll`, and `sqmapi.dll`. Those edges were missing from the previous objdump-regex graph.",
        "",
        "## Dynamic-resolution caveat",
        "",
        "`LoadLibrary*` and `GetProcAddress` imports occur in the corpus, so the static plus delay-load graph is still a lower bound. Recovering dynamically constructed module/symbol names requires string cross-references or runtime tracing and is out of scope for Phase 0.",
        "",
    ]
    return "\n".join(lines)


def render_module_readme(item: dict) -> str:
    pe = item["pe"]
    image: PeImage = item["_image"]
    section_rows = []
    for section in image.sections:
        flags = ", ".join(section.characteristics_names) or "—"
        section_rows.append(
            f"| `{section.name}` | 0x{section.virtual_size:x} | 0x{section.size_of_raw_data:x} | `0x{image.image_base + section.virtual_address:x}` | 0x{section.pointer_to_raw_data:x} | {flags} |"
        )
    directories = [
        f"| `{directory.name}` | `0x{directory.rva:x}` | 0x{directory.size:x} |"
        for directory in image.data_directories
        if directory.rva or directory.size
    ]
    static = grouped_symbols(image.imports)
    delayed = grouped_symbols(image.delay_imports)
    import_lines = [f"- `{dll}`: {len(names)} imports" for dll, names in static.items()] or ["- None recovered."]
    delay_lines = [f"- `{dll}`: {len(names)} delay-load imports" for dll, names in delayed.items()] or ["- None recovered."]
    export_line = ", ".join(f"`{sym.display()}`" for sym in image.exports) if image.exports else "none recovered"
    pdb = ", ".join(f"`{name}`" for name in pe["pdb"]) if pe["pdb"] else "none recovered"
    objdump_name = objdump_raw_name(ROOT / item["path"])
    return "\n".join(
        [
            f"# {Path(item['path']).name}",
            "",
            f"> Evidence status: header, section, import/export, delay-load, and debug-directory facts below are verified against SHA-256 `{item['sha256']}` using the stdlib PE parser and GNU objdump. Function types and behavior have not been guessed.",
            "",
            "## Image",
            "",
            f"- Path: `{item['path']}`",
            f"- Bytes: {item['size']:,}",
            f"- SHA-256: `{item['sha256']}`",
            f"- Format: `{pe['format']}`",
            f"- Machine: `{pe['machine']}`",
            f"- Entry point: `{pe['entry_va']}` (RVA `{pe['entry_rva']}`)",
            f"- ImageBase: `{pe['image_base']}`",
            f"- Subsystem: `{pe['subsystem']}`",
            f"- Linker: `{pe['linker_version']}`; OS version: `{pe['os_version']}`",
            f"- Characteristics: {', '.join(f'`{name}`' for name in pe['characteristics']) or 'none'}",
            f"- DllCharacteristics: {', '.join(f'`{name}`' for name in pe['dll_characteristics']) or 'none'}",
            f"- Timestamp field: `{pe['timestamp_utc']}` (untrusted PE metadata)",
            f"- CLR header present: `{pe['has_clr']}`",
            f"- CodeView PDB: {pdb}",
            "",
            "## Sections",
            "",
            "| Name | Virtual size | Raw size | VMA | File offset | Characteristics |",
            "|---|---:|---:|---|---:|---|",
            *section_rows,
            "",
            "## Data directories (non-empty)",
            "",
            "| Name | RVA | Size |",
            "|---|---|---:|",
            *(directories or ["| — | — | — |"]),
            "",
            "## Static imports",
            "",
            *import_lines,
            "",
            "## Delay-load imports",
            "",
            *delay_lines,
            "",
            "## Exports",
            "",
            export_line,
            "",
            "## Reconstruction status",
            "",
            f"No compatibility implementation is emitted: available evidence is insufficient to assign semantics safely. Raw structural evidence is in `analysis/report/generated/{objdump_name}` and `analysis/report/generated/pe-struct.json`.",
            "",
        ]
    )


def render_interfaces_h(item: dict) -> str:
    image: PeImage = item["_image"]
    header = [
        "#pragma once",
        "/*",
        f" * Evidence ledger for {Path(item['path']).name}",
        f" * SHA-256: {item['sha256']}",
        " *",
    ]
    if image.exports:
        header.append(" * Observed exports (names/ordinals only; types and calling")
        header.append(" * conventions are not asserted in Phase 0):")
        for symbol in image.exports:
            extra = f"  @ ordinal {symbol.ordinal}"
            if symbol.forwarder:
                extra += f"  forwarder {symbol.forwarder}"
            header.append(f" *   {symbol.display()}{extra}")
        header.append(" *")
        header.append(" * No callable declarations are emitted until signatures are recovered.")
    else:
        header.append(" * No exported symbols were recovered from the Export Address Table.")
        header.append(" * No callable declarations are emitted in Phase 0.")
    header.append(" */")
    header.append("")
    return "\n".join(header) + "\n"


def collect_files() -> tuple[list[dict], list[dict]]:
    files: list[dict] = []
    pe_records: list[dict] = []
    GEN.mkdir(parents=True, exist_ok=True)
    SRC.mkdir(exist_ok=True)
    for path in sorted(item for item in BIN.rglob("*") if item.is_file()):
        rel = path.relative_to(ROOT).as_posix()
        header = path.read_bytes()[:16]
        kind = classify(path, header)
        rec = {
            "path": rel,
            "size": path.stat().st_size,
            "sha256": sha256_file(path),
            "magic": header.hex(),
            "kind": kind,
        }
        if kind == "PE/COFF":
            dump = run_objdump(path)
            raw_path = GEN / objdump_raw_name(path)
            text = dump["stdout"]
            if dump["stderr"]:
                text += "\nSTDERR:\n" + str(dump["stderr"])
            write_text(raw_path, text)
            image = parse_pe(path.read_bytes())
            rec["objdump_exit"] = dump["exit_code"]
            rec["pe"] = pe_summary(image)
            pe_rec = {
                **rec,
                "_image": image,
            }
            pe_records.append(pe_rec)
        files.append(rec)
    return files, pe_records


def build_edges(pe_records: list[dict]) -> list[dict]:
    edges: list[dict] = []
    for item in pe_records:
        image: PeImage = item["_image"]
        for kind, symbols in (("static", image.imports), ("delay-load", image.delay_imports)):
            grouped = grouped_symbols(symbols)
            for dll, names in grouped.items():
                edges.append({"source": item["path"], "target": dll, "kind": kind, "symbols": names})
    return edges


def emit_ledgers(pe_records: list[dict]) -> None:
    for item in pe_records:
        path = ROOT / item["path"]
        directory = SRC / module_name(path)
        directory.mkdir(parents=True, exist_ok=True)
        write_text(directory / "README.md", render_module_readme(item))
        write_text(directory / "interfaces.h", render_interfaces_h(item))


def debug_rsds_index(pe_records: list[dict]) -> list[dict]:
    rows: list[dict] = []
    for item in pe_records:
        image: PeImage = item["_image"]
        for record in image.debug:
            if not record.pdb_path:
                continue
            rows.append(
                {
                    "path": item["path"],
                    "pdb": record.pdb_path,
                    "guid": record.guid,
                    "age": record.age,
                    "type": record.type_name,
                    "rva": f"0x{record.rva:x}",
                    "size": record.size,
                }
            )
    return rows


def public_pe_struct(pe_records: list[dict]) -> list[dict]:
    payload = []
    for item in pe_records:
        image: PeImage = item["_image"]
        payload.append(
            {
                "path": item["path"],
                "sha256": item["sha256"],
                "size": item["size"],
                "pe": image.to_dict(),
            }
        )
    return payload


def main() -> int:
    os.chdir(ROOT)
    files, pe_records = collect_files()
    edges = build_edges(pe_records)
    hashes = [{"path": item["path"], "size": item["size"], "sha256": item["sha256"], "kind": item["kind"]} for item in files]
    write_json(GEN / "inventory.json", files)
    write_json(GEN / "hashes.json", hashes)
    write_json(GEN / "dependencies.json", edges)
    write_json(GEN / "pe-struct.json", public_pe_struct(pe_records))
    write_json(GEN / "debug-rsds.json", debug_rsds_index(pe_records))
    write_text(REPORT / "inventory.md", render_inventory_md(files))
    write_text(REPORT / "api-map.md", render_api_map_md(pe_records))
    write_text(REPORT / "dependencies.md", render_dependencies_md(pe_records, edges))
    emit_ledgers(pe_records)
    print(f"Inventoried {len(files)} files, parsed {len(pe_records)} PE images.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
